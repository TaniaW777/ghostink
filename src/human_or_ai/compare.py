"""Compare model versions from the JSON reports only (no model is loaded, nothing is retrained).

Usage:
    python -m human_or_ai.compare --versions v1 v2

Reads reports/diagnosis/<version>/{test_metrics,cross_dataset,by_length,top_words}.json
and writes reports/comparison_<v1>_<v2>[...].md.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from human_or_ai.utils import load_config, resolve

# One line per evaluation: (label, how to find the metrics in the diagnosis files).
EVALUATIONS = [
    ("test (in-distribution)", "test"),
    ("cross: recent → abstracts", ("recent", "abstracts")),
    ("cross: abstracts → recent", ("abstracts", "recent")),
    ("test, texts < 50 words", "<50"),
]
TOP_K = 15


def _read(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def _pct(x) -> str:
    return "-" if x is None else f"{100 * x:.1f}%"


def _num(x) -> str:
    return "-" if x is None else f"{x:.3f}"


def evaluation_rows(diag_dir: Path) -> dict[str, dict]:
    """Metrics of one version for each evaluation of EVALUATIONS."""
    test = _read(diag_dir / "test_metrics.json")
    cross = _read(diag_dir / "cross_dataset.json")
    by_length = {row["group"]: row for row in _read(diag_dir / "by_length.json")}
    rows = {}
    for label, key in EVALUATIONS:
        if key == "test":
            rows[label] = test
        elif isinstance(key, tuple):
            rows[label] = next(r for r in cross if (r["train_on"], r["test_on"]) == key)
        else:
            rows[label] = by_length[key]
    return rows


def metrics_table(versions: list[str], reports_dir: Path) -> str:
    lines = [
        "| Evaluation | Version | Accuracy | FPR human ↓ | TPR AI ↑ | ROC-AUC | ECE ↓ | Texts |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    per_version = {v: evaluation_rows(reports_dir / "diagnosis" / v) for v in versions}
    for label, _ in EVALUATIONS:
        for v in versions:
            m = per_version[v][label]
            lines.append(
                f"| {label} | {v} | {_pct(m['accuracy'])} | {_pct(m['fpr_human'])} | {_pct(m['tpr_ai'])} "
                f"| {_num(m['roc_auc'])} | {_num(m['ece'])} | {m['n']:,} |"
            )
    return "\n".join(lines)


def top_words_table(versions: list[str], reports_dir: Path, k: int = TOP_K) -> str:
    """Rank i: the i-th most human and the i-th most AI word of each version."""
    words = {}
    for v in versions:
        top = _read(reports_dir / "diagnosis" / v / "top_words.json")
        # top_words.json lists the human side first (most human first), then the AI side (most AI first).
        words[v] = {side: [r["word"] for r in top if r["side"] == side][:k] for side in ("human", "ai")}
    header = ["Rank"] + [f"{v} human" for v in versions] + [f"{v} AI" for v in versions]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(["---:"] + ["---"] * (len(header) - 1)) + "|"]
    for i in range(k):
        cells = [str(i + 1)]
        for side in ("human", "ai"):
            for v in versions:
                lst = words[v][side]
                cells.append(f"`{lst[i]}`" if i < len(lst) else "-")
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> Path:
    parser = argparse.ArgumentParser(description="Compare model versions from their JSON reports.")
    parser.add_argument("--versions", nargs="+", required=True, help="Versions to compare, e.g. v1 v2.")
    parser.add_argument("--config", default=None, help="Config used only for the reports path.")
    args = parser.parse_args(argv)

    reports_dir = resolve(load_config(args.config)["paths"]["reports"])
    versions = args.versions
    md = [
        f"# Comparison: {' vs '.join(versions)}",
        "",
        "Auto-generated by `python -m human_or_ai.compare --versions " + " ".join(versions) + "` "
        "from `reports/diagnosis/<version>/*.json`. Do not edit by hand.",
        "",
        "Threshold 0.5, label 1 = AI. Cross lines: model retrained on one dataset only, "
        "tested on the other dataset's test split. `< 50 words`: test texts shorter than 50 words.",
        "",
        "## Metrics",
        "",
        metrics_table(versions, reports_dir),
        "",
        f"## Top {TOP_K} words",
        "",
        "Most human and most AI words from the learned weights (`top_words.json`), rank 1 = strongest.",
        "",
        top_words_table(versions, reports_dir),
    ]
    out = reports_dir / f"comparison_{'_'.join(versions)}.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(f"Saved comparison to {out}")
    return out


if __name__ == "__main__":
    main()
