"""Decision thresholds on the v2 validation set, then verdicts on the v2 test set.

Usage:
    python -m human_or_ai.decision_report --config configs/v2.yaml

Writes artifacts/<version>/calibration.json, reports/decision_<version>.json and
reports/decision_<version>.md. No training: the saved model is only used for predictions.
"""

from __future__ import annotations

import argparse
import json

import numpy as np

from human_or_ai.utils import load_config, resolve, set_seed


def decision_metrics(y_true, verdicts) -> dict:
    """Coverage, share of each abstention, and FPR / FNR / accuracy on the decided texts only."""
    y_true = np.asarray(y_true).astype(int)
    verdicts = np.asarray(verdicts)
    n = len(y_true)
    decided = np.isin(verdicts, ["Human", "AI"])
    pred_ai = verdicts == "AI"
    human_dec = decided & (y_true == 0)
    ai_dec = decided & (y_true == 1)
    correct = decided & (pred_ai == (y_true == 1))
    return {
        "n": int(n),
        "n_decided": int(decided.sum()),
        "coverage": float(decided.mean()) if n else None,
        "uncertain_share": float((verdicts == "Uncertain").mean()) if n else None,
        "not_enough_text_share": float((verdicts == "Not enough text").mean()) if n else None,
        # Human texts called "AI", among the decided human texts.
        "fpr_decided": float((human_dec & pred_ai).sum() / human_dec.sum()) if human_dec.any() else None,
        # AI texts called "Human", among the decided AI texts.
        "fnr_decided": float((ai_dec & ~pred_ai).sum() / ai_dec.sum()) if ai_dec.any() else None,
        "accuracy_decided": float(correct.sum() / decided.sum()) if decided.any() else None,
        "verdict_counts": {v: int((verdicts == v).sum()) for v in ("Human", "AI", "Uncertain", "Not enough text")},
    }


def _pct(x) -> str:
    return "-" if x is None else f"{100 * x:.1f}%"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Decision thresholds and verdict report.")
    parser.add_argument("--config", default="configs/v2.yaml")
    args = parser.parse_args(argv)

    config = load_config(resolve(args.config))
    set_seed(config["seed"])

    import keras

    import human_or_ai.models  # noqa: F401  registers custom_standardization for loading
    from human_or_ai.calibrate import choose_thresholds, decide
    from human_or_ai.data import load_splits
    from human_or_ai.diagnose import predict_texts
    from human_or_ai.evaluate import word_counts

    version = config["model"]["version"]
    dec_cfg = config["decision"]
    splits = load_splits(config)
    model_dir = resolve(config["paths"]["artifacts"]) / version
    export = keras.models.load_model(model_dir / "model.keras", compile=False)

    # 1. Thresholds on the validation set.
    p_val = predict_texts(export, splits.val["text"])
    thresholds = choose_thresholds(splits.val["label"], p_val, dec_cfg["target_fpr"], dec_cfg["target_fnr"])
    calibration = {
        "t_human": thresholds["t_human"],
        "t_ai": thresholds["t_ai"],
        "min_words": dec_cfg["min_words"],
        "target_fpr": dec_cfg["target_fpr"],
        "target_fnr": dec_cfg["target_fnr"],
        "model_version": version,
        "seed": config["seed"],
    }
    (model_dir / "calibration.json").write_text(json.dumps(calibration, indent=2), encoding="utf-8", newline="\n")

    # 2. Verdicts on the test set.
    test = splits.test
    p_test = predict_texts(export, test["text"])
    n_words = word_counts(test["text"])
    verdicts = [
        decide(float(p), int(w), thresholds["t_human"], thresholds["t_ai"], dec_cfg["min_words"])
        for p, w in zip(p_test, n_words, strict=True)
    ]
    rows = [{"evaluation": f"test {version}", **decision_metrics(test["label"], verdicts)}]

    reports_dir = resolve(config["paths"]["reports"])
    reports_dir.mkdir(parents=True, exist_ok=True)
    out = {"calibration": calibration, "rows": rows}
    (reports_dir / f"decision_{version}.json").write_text(json.dumps(out, indent=2), encoding="utf-8", newline="\n")

    md = [
        f"# Decision report: {version}",
        "",
        "Auto-generated by `python -m human_or_ai.decision_report`. Do not edit by hand.",
        "",
        "## Thresholds (chosen on the validation set)",
        f"- t_human = {calibration['t_human']:.4f} (P(AI) at or below: verdict Human)",
        f"- t_ai = {calibration['t_ai']:.4f} (P(AI) at or above: verdict AI)",
        f"- min_words = {calibration['min_words']} (fewer words: verdict Not enough text)",
        f"- target_fpr = {calibration['target_fpr']}, target_fnr = {calibration['target_fnr']}",
        "",
        "## Verdicts",
        "Coverage = share of texts that get a Human or AI verdict. FPR, FNR and accuracy are computed "
        "on the decided texts only.",
        "",
        "| evaluation | n | coverage | uncertain | not enough text | FPR (decided) | FNR (decided) "
        "| accuracy (decided) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        md.append(
            f"| {r['evaluation']} | {r['n']} | {_pct(r['coverage'])} | {_pct(r['uncertain_share'])} "
            f"| {_pct(r['not_enough_text_share'])} | {_pct(r['fpr_decided'])} | {_pct(r['fnr_decided'])} "
            f"| {_pct(r['accuracy_decided'])} |"
        )
    (reports_dir / f"decision_{version}.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
