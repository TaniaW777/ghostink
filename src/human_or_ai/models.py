"""Model definitions. One function per version; every version evolves from v1."""

from __future__ import annotations

import re
import string

import keras
import tensorflow as tf
from keras import layers

# Regex that matches any ASCII punctuation character.
_PUNCTUATION = f"[{re.escape(string.punctuation)}]"


@keras.saving.register_keras_serializable(package="human_or_ai")
def custom_standardization(input_data):
    """v1 text cleaning: lowercase, replace HTML tags by a space, remove punctuation."""
    lowercase = tf.strings.lower(input_data, encoding="utf-8")
    stripped_html = tf.strings.regex_replace(lowercase, "<[^>]+>", " ")
    return tf.strings.regex_replace(stripped_html, _PUNCTUATION, "")


def build_vectorizer(max_tokens: int, sequence_length: int) -> layers.TextVectorization:
    """Word-level vectorizer: each text becomes a fixed-length list of word ids."""
    return layers.TextVectorization(
        standardize=custom_standardization,
        max_tokens=max_tokens,
        output_mode="int",
        output_sequence_length=sequence_length,
    )


def freeze_vectorizer(vectorizer: layers.TextVectorization) -> layers.TextVectorization:
    """Copy an adapted vectorizer with its vocabulary stored in the layer config.

    Keras 3.15 writes adapted vocabularies to a text file with the system encoding,
    which fails on Windows (cp1252) for words like "α". A vocabulary passed to the
    constructor is saved in the JSON config instead, which is always UTF-8.
    """
    cfg = vectorizer.get_config()
    frozen = layers.TextVectorization(
        standardize=vectorizer._standardize,
        split=cfg["split"],
        max_tokens=cfg["max_tokens"],
        output_mode=cfg["output_mode"],
        output_sequence_length=cfg["output_sequence_length"],
        ngrams=cfg["ngrams"],
        vocabulary=vectorizer.get_vocabulary(),
    )
    # Same words in the same order, so the same ids: behaviour is unchanged.
    assert frozen.get_vocabulary() == vectorizer.get_vocabulary()
    return frozen


def build_v1(max_tokens: int, sequence_length: int, embedding_dim: int = 16, dropout: float = 0.2) -> keras.Model:
    """v1 baseline from the notebook: Embedding -> Dropout -> average -> Dropout -> sigmoid."""
    model = keras.Sequential(
        [
            keras.Input(shape=(sequence_length,), dtype="int64"),
            # Each word id becomes a 16-number vector; padding zeros are masked out.
            layers.Embedding(max_tokens, embedding_dim, mask_zero=True),
            layers.Dropout(dropout),
            # Average the word vectors into one vector per text (masked positions ignored).
            layers.GlobalAveragePooling1D(),
            layers.Dropout(dropout),
            # Probability that the text was generated by an AI.
            layers.Dense(1, activation="sigmoid"),
        ],
        name="v1",
    )
    model.compile(
        loss=keras.losses.BinaryCrossentropy(),
        optimizer="adam",
        metrics=[keras.metrics.BinaryAccuracy(threshold=0.5)],
    )
    return model


def build_export_model(vectorizer: layers.TextVectorization, model: keras.Model) -> keras.Model:
    """Wrap vectorizer + trained model so the saved model accepts raw text."""
    # No extra sigmoid here: the model already ends with one.
    export = keras.Sequential([keras.Input(shape=(), dtype="string"), vectorizer, model], name=f"{model.name}_export")
    export.compile(loss=keras.losses.BinaryCrossentropy(), optimizer="adam", metrics=["accuracy"])
    return export


# v2 keeps the v1 architecture; only the data changes (normalization, see configs/v2.yaml).
build_v2 = build_v1

MODEL_BUILDERS = {"v1": build_v1, "v2": build_v2}
