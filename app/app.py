"""Gradio interface for the "Ghostink" detector.

Usage (from the repository root):
    python app/app.py
"""

from __future__ import annotations

import json
from pathlib import Path

import gradio as gr

from human_or_ai.normalize import normalize_text
from human_or_ai.predict import Detector
from human_or_ai.shortcuts import standardize

EXAMPLES_PATH = Path(__file__).resolve().parent / "examples.json"
README_URL = "https://github.com/TaniaW777/ghostink#readme"

COLORS = {"AI": "#1d4ed8", "Human": "#047857", "Uncertain": "#b45309", "Not enough text": "#64748b"}
HEADLINES = {
    "AI": "Likely AI-generated",
    "Human": "Likely human-written",
    "Uncertain": "Uncertain",
    "Not enough text": "Not enough text",
}
WARNING = (
    "These are statistical signals learned from two public datasets, not proof. Never use this tool to accuse someone."
)

CSS = """
.gradio-container {max-width: 1100px !important; margin: auto;}
#header h1 {font-size: 1.7rem; font-weight: 700; margin-bottom: 0;}
#header p {color: var(--body-text-color-subdued); margin-top: 4px;}
.card {border: 1px solid var(--border-color-primary); border-radius: 12px; padding: 20px;
       background: var(--block-background-fill);}
.card-label {font-size: 0.8rem; text-transform: uppercase; letter-spacing: 0.06em;
             color: var(--body-text-color-subdued);}
.verdict {font-size: 1.4rem; font-weight: 700; margin: 8px 0 16px;}
.gauge {position: relative; height: 10px; border-radius: 5px; background: #e2e8f0;}
.gauge-fill {height: 100%; border-radius: 5px;}
.gauge-mark {position: absolute; top: -4px; width: 2px; height: 18px; background: #334155;}
.gauge-legend {display: flex; justify-content: space-between; font-size: 0.85rem; margin-top: 6px;
               color: var(--body-text-color-subdued);}
.details {margin-top: 14px; font-size: 0.95rem;}
.thresholds {margin-top: 8px; font-size: 0.85rem; color: var(--body-text-color-subdued);}
#warning {border-left: 4px solid #b45309; padding: 8px 14px; background: var(--block-background-fill);}
"""

detector = Detector.load("artifacts/v2")
calibration = detector.calibration
examples = json.loads(EXAMPLES_PATH.read_text(encoding="utf-8"))


def empty_card(message: str) -> str:
    return f"<div class='card'><div class='card-label'>{message}</div></div>"


def result_card(result: dict) -> str:
    verdict = result["verdict"]
    color = COLORS[verdict]
    p_ai = result["p_ai"]
    t_human, t_ai, min_words = calibration["t_human"], calibration["t_ai"], calibration["min_words"]
    if verdict == "Not enough text":
        details = f"{result['n_words']} words analysed; at least {min_words} words are needed for a verdict."
    else:
        details = f"P(AI): <b>{p_ai:.0%}</b> &middot; {result['n_words']} words analysed"
    return f"""
    <div class='card'>
      <div class='card-label'>Result</div>
      <div class='verdict' style='color:{color}'>{HEADLINES[verdict]}</div>
      <div class='gauge'>
        <div class='gauge-fill' style='width:{p_ai * 100:.1f}%; background:{color}'></div>
        <div class='gauge-mark' style='left:{t_human * 100:.1f}%'></div>
        <div class='gauge-mark' style='left:{t_ai * 100:.1f}%'></div>
      </div>
      <div class='gauge-legend'><span>Human</span><span>P(AI)</span><span>AI</span></div>
      <div class='details'>{details}</div>
      <div class='thresholds'>Thresholds: Human if P(AI) &le; {t_human:.2f}, AI if P(AI) &ge; {t_ai:.2f},
        Uncertain in between; minimum {min_words} words.</div>
    </div>"""


def highlight(text: str, signals: list[tuple[str, float]]) -> list[tuple[str, str | None]]:
    """Each word of the normalized text, tagged with its signal when it is one of the strongest words."""
    scores = dict(signals)
    pieces = []
    for word in normalize_text(text).split():
        score = scores.get(standardize(word).strip())
        if score is None:
            pieces.append((word + " ", None))
        else:
            pieces.append((word + " ", "AI signal" if score > 0 else "Human signal"))
    return pieces


def count_words(text: str) -> str:
    n_words = len(normalize_text(text or "").split())
    return f"{n_words} words (minimum {calibration['min_words']})"


def analyze(text: str):
    if not text or not text.strip():
        return empty_card("Paste a text to start the analysis."), []
    result = detector.predict([text])[0]
    return result_card(result), highlight(text, result["signals"])


with gr.Blocks(title="Ghostink") as demo:
    gr.Markdown(
        "# Ghostink\n"
        "Paste an English text: a small neural network trained from scratch estimates whether it was "
        "written by a human or generated by an AI.",
        elem_id="header",
    )
    with gr.Tab("Detector"):
        with gr.Row():
            with gr.Column(scale=3):
                text_input = gr.Textbox(label="Text to analyze", lines=12, placeholder="Paste an English text here...")
                word_count = gr.Markdown(count_words(""))
                with gr.Row():
                    clear_button = gr.Button("Clear")
                    analyze_button = gr.Button("Analyze", variant="primary")
            with gr.Column(scale=2):
                result_html = gr.HTML(empty_card("The result will appear here."))
        signals_output = gr.HighlightedText(
            label="Signals (words that weighed most in the decision)",
            color_map={"AI signal": "#93c5fd", "Human signal": "#6ee7b7"},
            show_legend=True,
        )
        gr.Examples(
            examples=[[example["text"]] for example in examples],
            inputs=text_input,
            label="Examples",
            example_labels=[example["label"] for example in examples],
        )
    with gr.Tab("About"):
        gr.Markdown(
            "- **Principle**: a small Keras network (Embedding + average pooling + Dense) trained from scratch "
            "on two public Hugging Face datasets of human and AI texts.\n"
            "- **Decision**: the model gives P(AI); thresholds calibrated on the validation set turn it into "
            "Human, AI or Uncertain, and short texts get no verdict.\n"
            "- **Signals**: highlighted words are those whose learned weight pushed the score most.\n"
            "- **Limits**: English only, learned from two datasets only, so texts from other sources, "
            "styles or periods may be misjudged; a verdict is never proof.\n"
            f"- **More**: methods, results and limitations in the [README]({README_URL})."
        )
    gr.Markdown(WARNING, elem_id="warning")

    text_input.change(count_words, inputs=text_input, outputs=word_count)
    analyze_button.click(analyze, inputs=text_input, outputs=[result_html, signals_output])
    clear_button.click(
        lambda: ("", empty_card("The result will appear here."), []),
        outputs=[text_input, result_html, signals_output],
    )


if __name__ == "__main__":
    demo.launch(
        inbrowser=True,
        theme=gr.themes.Base(
            primary_hue="blue", neutral_hue="slate", font=[gr.themes.GoogleFont("Inter"), "sans-serif"]
        ),
        css=CSS,
    )
